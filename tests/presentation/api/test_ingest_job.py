def _make_job(
    *,
    job_id: str = "job-001",
    status: IngestJobStatus = IngestJobStatus.PENDING,
) -> IngestJob:
    return IngestJob(
        id=job_id,
        source_type=SourceType.CONFLUENCE,
        status=status,
        started_at=datetime(2026, 7, 15, 10, 0, 0, tzinfo=UTC),
        completed_at=None,
        error=None,
        stats={"chunks": 0},
    )


@pytest.mark.asyncio
async def test_create_ingest_job_success(api_client):
    client, ingest_job_repo = api_client

    response = await client.post(
        "/api/v1/ingest-jobs",
        json={
            "source_type": "CONFLUENCE",
            "stats": {"chunks": 0},
        },
    )

    assert response.status_code == 201
    payload = response.json()
    assert payload["source_type"] == "CONFLUENCE"
    assert payload["status"] == "pending"
    assert payload["stats"] == {"chunks": 0}
    assert payload["id"]  # UUID generated by server
    assert payload["started_at"]  # timestamp generated by server
    ingest_job_repo.create.assert_awaited_once()


@pytest.mark.asyncio
async def test_get_ingest_job_success(api_client):
    client, ingest_job_repo = api_client
    job = _make_job(status=IngestJobStatus.RUNNING)
    ingest_job_repo.get_by_id.return_value = job

    response = await client.get("/api/v1/ingest-jobs/job-001")

    assert response.status_code == 200
    payload = response.json()
    assert payload["id"] == "job-001"
    assert payload["status"] == "running"
    assert payload["source_type"] == "CONFLUENCE"


