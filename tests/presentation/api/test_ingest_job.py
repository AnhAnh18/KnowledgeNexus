@pytest.mark.asyncio
async def test_update_ingest_job_success(api_client):
    client, ingest_job_repo = api_client
    existing = _make_job(status=IngestJobStatus.PENDING)
    ingest_job_repo.get_by_id.return_value = existing

    response = await client.patch(
        "/api/v1/ingest-jobs/job-001",
        json={
            "status": "completed",
            "completed_at": "2026-07-15T11:00:00Z",
            "stats": {"chunks": 50, "documents": 5},
        },
    )

    assert response.status_code == 200
    payload = response.json()
    assert payload["status"] == "completed"
    assert payload["stats"] == {"chunks": 50, "documents": 5}
    ingest_job_repo.update.assert_awaited_once()
    updated_job = ingest_job_repo.update.await_args.args[0]
    assert updated_job.status == IngestJobStatus.COMPLETED


